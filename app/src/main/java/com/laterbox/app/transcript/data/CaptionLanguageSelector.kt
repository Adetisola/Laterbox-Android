package com.laterbox.app.transcript.data

import com.laterbox.app.transcript.domain.CaptionTrackCandidate

data class SelectedCaptionSource(
    val track: CaptionTrackCandidate,
    val format: String,
    val url: String
)

object CaptionLanguageSelector {

    private val FORMAT_PREFERENCE = listOf("json3", "vtt", "srv3", "srv1", "ttml")

    private val ENGLISH_PRIORITY = listOf(
        "en",
        "en-us",
        "en-gb",
        "en-ca",
        "en-au",
        "en-nz",
        "en-ie",
        "en-in",
        "en-orig"
    )

    fun selectBest(tracks: List<CaptionTrackCandidate>): SelectedCaptionSource? {
        if (tracks.isEmpty()) return null

        val viableTracks = tracks.filter { it.formatUrls.isNotEmpty() }
        if (viableTracks.isEmpty()) return null

        val rankedTrack = viableTracks.minWithOrNull(
            compareBy<CaptionTrackCandidate>(
                { languageRank(it.languageCode) },
                { if (it.isAutoGenerated) 1 else 0 },
                { subLanguageOrder(it.languageCode) }
            )
        ) ?: return null

        val bestFormat = selectBestFormat(rankedTrack.formatUrls) ?: return null
        return SelectedCaptionSource(
            track = rankedTrack,
            format = bestFormat.first,
            url = bestFormat.second
        )
    }

    fun selectBestFormat(formatUrls: Map<String, String>): Pair<String, String>? {
        if (formatUrls.isEmpty()) return null
        val lowerMap = formatUrls.entries.associate { it.key.lowercase() to it.value }
        for (fmt in FORMAT_PREFERENCE) {
            val url = lowerMap[fmt]
            if (!url.isNullOrBlank()) {
                return fmt to url
            }
        }
        val first = formatUrls.entries.firstOrNull { it.value.isNotBlank() } ?: return null
        return first.key.lowercase() to first.value
    }

    fun formatDisplayLanguage(track: CaptionTrackCandidate): String {
        val cleanName = track.languageName
            ?.replace(Regex("\\s*\\(auto-generated\\)\\s*", RegexOption.IGNORE_CASE), "")
            ?.trim()
            ?.takeIf { it.isNotBlank() }
        if (cleanName != null) return cleanName

        val code = track.languageCode.trim().lowercase()
        return when {
            code == "en" || code.startsWith("en-") -> "English"
            code.startsWith("es") -> "Spanish"
            code.startsWith("fr") -> "French"
            code.startsWith("de") -> "German"
            code.startsWith("pt") -> "Portuguese"
            code.startsWith("it") -> "Italian"
            code.startsWith("ja") -> "Japanese"
            code.startsWith("ko") -> "Korean"
            code.startsWith("zh") -> "Chinese"
            code.startsWith("hi") -> "Hindi"
            code.startsWith("ar") -> "Arabic"
            code.startsWith("ru") -> "Russian"
            else -> track.languageCode.ifBlank { "Unknown" }
        }
    }

    private fun languageRank(languageCode: String): Int {
        val norm = languageCode.trim().lowercase()
        if (norm == "en" || norm == "en-orig" || norm.startsWith("en-")) return 0
        return 1
    }

    private fun subLanguageOrder(languageCode: String): Int {
        val norm = languageCode.trim().lowercase()
        val exact = ENGLISH_PRIORITY.indexOf(norm)
        if (exact >= 0) return exact
        if (norm.startsWith("en-")) return ENGLISH_PRIORITY.size
        return ENGLISH_PRIORITY.size + 1
    }
}
