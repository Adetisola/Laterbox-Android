package com.laterbox.app.transcript.data

import com.laterbox.app.transcript.domain.CaptionTrackCandidate

data class SelectedCaptionSource(
    val track: CaptionTrackCandidate,
    val format: String,
    val url: String
)

object CaptionLanguageSelector {

    private val TRANSLATED_PARAM_REGEX = Regex("""[?&]tlang=[^&#]+""", RegexOption.IGNORE_CASE)

    private val FORMAT_PREFERENCE = listOf("json3", "vtt", "srv3", "srv1", "ttml")

    private val ENGLISH_PRIORITY = listOf(
        "en",
        "en-orig",
        "en-us",
        "en-gb",
        "en-ca",
        "en-au",
        "en-nz",
        "en-ie",
        "en-in"
    )

    fun hasAutoTranslateParam(url: String): Boolean {
        return url.isNotBlank() && TRANSLATED_PARAM_REGEX.containsMatchIn(url)
    }

    fun isTrackAutoTranslated(track: CaptionTrackCandidate): Boolean {
        if (track.inlineContentByFormat.isNotEmpty()) return false
        if (track.formatUrls.isEmpty()) return false
        return track.formatUrls.values.all { hasAutoTranslateParam(it) }
    }

    fun selectBest(tracks: List<CaptionTrackCandidate>): SelectedCaptionSource? {
        return selectRankedSources(tracks).firstOrNull()
    }

    fun selectRankedSources(tracks: List<CaptionTrackCandidate>): List<SelectedCaptionSource> {
        if (tracks.isEmpty()) return emptyList()

        val viableTracks = tracks.filter { it.formatUrls.isNotEmpty() || it.inlineContentByFormat.isNotEmpty() }
        if (viableTracks.isEmpty()) return emptyList()

        val sortedTracks = viableTracks.sortedWith(
            compareBy<CaptionTrackCandidate>(
                { languageRank(it.languageCode) },
                { if (isTrackAutoTranslated(it)) 1 else 0 },
                { if (it.isAutoGenerated) 1 else 0 },
                { subLanguageOrder(it.languageCode) }
            )
        )

        return sortedTracks.mapNotNull { track ->
            val bestInline = selectBestInlineFormat(track.inlineContentByFormat)
            if (bestInline != null) {
                SelectedCaptionSource(
                    track = track,
                    format = bestInline,
                    url = track.formatUrls[bestInline] ?: "native://${track.languageCode}.$bestInline"
                )
            } else {
                val bestFormat = selectBestFormat(track.formatUrls) ?: return@mapNotNull null
                SelectedCaptionSource(
                    track = track,
                    format = bestFormat.first,
                    url = bestFormat.second
                )
            }
        }
    }

    private fun selectBestInlineFormat(inlineMap: Map<String, String>): String? {
        if (inlineMap.isEmpty()) return null
        val lowerMap = inlineMap.entries.associate { it.key.lowercase() to it.value }
        for (fmt in FORMAT_PREFERENCE) {
            if (!lowerMap[fmt].isNullOrBlank()) return fmt
        }
        return inlineMap.entries.firstOrNull { it.value.isNotBlank() }?.key?.lowercase()
    }

    fun selectBestFormat(formatUrls: Map<String, String>): Pair<String, String>? {
        if (formatUrls.isEmpty()) return null
        val lowerMap = formatUrls.entries.associate { it.key.lowercase() to it.value }
        for (fmt in FORMAT_PREFERENCE) {
            val url = lowerMap[fmt]
            if (!url.isNullOrBlank() && !hasAutoTranslateParam(url)) {
                return fmt to url
            }
        }
        for (fmt in FORMAT_PREFERENCE) {
            val url = lowerMap[fmt]
            if (!url.isNullOrBlank()) {
                return fmt to url
            }
        }
        val firstUntranslated = formatUrls.entries.firstOrNull { it.value.isNotBlank() && !hasAutoTranslateParam(it.value) }
        if (firstUntranslated != null) {
            return firstUntranslated.key.lowercase() to firstUntranslated.value
        }
        val first = formatUrls.entries.firstOrNull { it.value.isNotBlank() } ?: return null
        return first.key.lowercase() to first.value
    }

    fun formatDisplayLanguage(track: CaptionTrackCandidate): String {
        val cleanName = track.languageName
            ?.replace(Regex("\\s*\\(auto-generated\\)\\s*", RegexOption.IGNORE_CASE), "")
            ?.replace(Regex("\\s*\\(Original\\)\\s*", RegexOption.IGNORE_CASE), "")
            ?.trim()
            ?.takeIf { it.isNotBlank() }
        if (cleanName != null) return cleanName

        val code = track.languageCode.trim().lowercase()
        return when {
            code == "en" || code == "en-orig" || code.startsWith("en-") -> "English"
            code.startsWith("es") -> "Spanish"
            code.startsWith("fr") -> "French"
            code.startsWith("de") -> "German"
            code.startsWith("pt") -> "Portuguese"
            code.startsWith("it") -> "Italian"
            code.startsWith("ja") -> "Japanese"
            code.startsWith("ko") -> "Korean"
            code.startsWith("zh") -> "Chinese"
            code.startsWith("hi") -> "Hindi"
            code.startsWith("ar") -> "Arabic"
            code.startsWith("ru") -> "Russian"
            else -> track.languageCode.ifBlank { "Unknown" }
        }
    }

    private fun languageRank(languageCode: String): Int {
        val norm = languageCode.trim().lowercase()
        if (norm == "en" || norm == "en-orig" || norm.startsWith("en-")) return 0
        return 1
    }

    private fun subLanguageOrder(languageCode: String): Int {
        val norm = languageCode.trim().lowercase()
        val exact = ENGLISH_PRIORITY.indexOf(norm)
        if (exact >= 0) return exact
        if (norm.startsWith("en-")) return ENGLISH_PRIORITY.size
        return ENGLISH_PRIORITY.size + 1
    }
}
