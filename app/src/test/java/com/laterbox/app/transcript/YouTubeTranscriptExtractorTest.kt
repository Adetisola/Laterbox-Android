    private class FakeTranscriptDataSource(
        private val videos: Map<String, VideoInfoFetchResult>,
        private val playlists: Map<String, PlaylistFetchResult> = emptyMap(),
        private val payloads: Map<String, suspend () -> Result<String>> = emptyMap(),
        private val perVideoDelayMs: Long = 0L
    ) : YouTubeTranscriptDataSource {

        val cancelledProcesses = mutableListOf<String>()

        override suspend fun fetchVideoInfo(
            videoId: String,
            videoUrl: String,
            processId: String
        ): VideoInfoFetchResult {
            if (perVideoDelayMs > 0L) delay(perVideoDelayMs)
            return videos[videoId] ?: VideoInfoFetchResult.Failed(
                status = VideoTranscriptStatus.UNAVAILABLE,
                message = "Video $videoId unavailable"
            )
        }

        override suspend fun fetchPlaylistEntries(
            playlistId: String,
            playlistUrl: String,
            processId: String,
            onPageLoaded: suspend (loadedCount: Int, totalEstimate: Int?) -> Unit
        ): PlaylistFetchResult {
            val res = playlists[playlistId] ?: return PlaylistFetchResult.Failed(
                status = VideoTranscriptStatus.UNAVAILABLE,
                message = "Playlist not found"
            )
            if (res is PlaylistFetchResult.Success) {
                onPageLoaded(res.playlist.entries.size, res.playlist.totalCountHint)
            }
            return res
        }

        override suspend fun fetchCaptionPayload(url: String): Result<String> {
            return payloads[url]?.invoke() ?: Result.failure(IllegalStateException("Missing payload for $url"))
        }

        override fun cancelProcess(processId: String) {
            cancelledProcesses.add(processId)
        }
    }

    @Test
    fun extract_singleVideoSuccess_preservesVerbatimCaptionsAndMetadata() = runTest {
        val captionUrl = "https://captions.test/v1.json3"
        val ds = FakeTranscriptDataSource(
            videos = mapOf(
                "vid001" to VideoInfoFetchResult.Success(
                    FetchedVideoInfo(
                        videoId = "vid001",
                        title = "Understanding Product Growth",
                        url = "https://www.youtube.com/watch?v=vid001",
                        channel = "Product Builders",
                        durationSeconds = 1475L,
                        captionTracks = listOf(
                            CaptionTrackCandidate(
                                languageCode = "en",
                                languageName = "English",
                                isAutoGenerated = true,
                                formatUrls = mapOf("json3" to captionUrl)
                            )
                        )
                    )
                )
            ),
            payloads = mapOf(
                captionUrl to {
                    Result.success(
                        """{"events":[{"tStartMs":0,"dDurationMs":2000,"segs":[{"utf8":"Transcript begins here verbatim."}]}]}"""
                    )
                }
            )
        )

        val extractor = YouTubeTranscriptExtractor(ds, clock = { 1700000000000L })
        val outcome = extractor.extract("https://www.youtube.com/watch?v=vid001")

        assertTrue(outcome is TranscriptExtractionOutcome.Completed)
        val doc = (outcome as TranscriptExtractionOutcome.Completed).document
        assertFalse(doc.isPlaylist)
        assertEquals(1, doc.videosFound)
        assertEquals(1, doc.successfulCount)
        assertEquals(0, doc.noCaptionsCount)
        assertEquals(0, doc.inaccessibleCount)
        val entry = doc.entries.single()
        assertEquals("Understanding Product Growth", entry.title)
        assertEquals("Product Builders", entry.channel)
        assertEquals(CaptionType.AUTOMATIC, entry.captionType)
        assertEquals("English", entry.captionLanguage)
        assertEquals("Transcript begins here verbatim.", entry.paragraphs.single().text)
    }

    @Test
    fun extract_singleVideoWithoutCaptions_reportsUnavailableWithoutFabricatingContent() = runTest {
        val ds = FakeTranscriptDataSource(
            videos = mapOf(
                "vid_nocap" to VideoInfoFetchResult.Success(
                    FetchedVideoInfo(
                        videoId = "vid_nocap",
                        title = "Silent Video",
                        url = "https://www.youtube.com/watch?v=vid_nocap",
                        captionTracks = emptyList()
                    )
                )
            )
        )
        val extractor = YouTubeTranscriptExtractor(ds)
        val outcome = extractor.extract("https://youtu.be/vid_nocap") as TranscriptExtractionOutcome.Completed
        val doc = outcome.document
        assertEquals(0, doc.successfulCount)
        assertEquals(1, doc.noCaptionsCount)
        assertFalse(doc.hasAnySuccessfulTranscript)
        assertEquals(VideoTranscriptStatus.NO_CAPTIONS, doc.entries.single().status)
        assertTrue(doc.entries.single().paragraphs.isEmpty())
    }

    @Test
    fun extract_playlistWithMixedResults_preservesOrderContinuesOnFailureAndReportsAccurateCounts() = runTest {
        val cap1 = "https://captions.test/p1.vtt"
        val cap3 = "https://captions.test/p3.json3"
        val ds = FakeTranscriptDataSource(
            playlists = mapOf(
                "PLmixed" to PlaylistFetchResult.Success(
                    PlaylistResolution(
                        playlistId = "PLmixed",
                        title = "Product Strategy Series",
                        sourceUrl = "https://www.youtube.com/playlist?list=PLmixed",
                        totalCountHint = 4,
                        entries = listOf(
                            PlaylistEntrySummary(1, "v1", "Video One", "https://www.youtube.com/watch?v=v1"),
                            PlaylistEntrySummary(2, "v2", "No Captions Video", "https://www.youtube.com/watch?v=v2"),
                            PlaylistEntrySummary(3, "v3", "Video Three", "https://www.youtube.com/watch?v=v3"),
                            PlaylistEntrySummary(
                                position = 4,
                                videoId = "v4",
                                title = "[Private video]",
                                url = "https://www.youtube.com/watch?v=v4",
                                unavailableReason = "Video is private and could not be accessed.",
                                unavailabilityStatus = VideoTranscriptStatus.ACCESS_ERROR
                            )
                        )
                    )
                )
            ),
            videos = mapOf(
                "v1" to VideoInfoFetchResult.Success(
                    FetchedVideoInfo(
                        videoId = "v1",
                        title = "Video One",
                        url = "https://www.youtube.com/watch?v=v1",
                        captionTracks = listOf(CaptionTrackCandidate("en", "English", false, mapOf("vtt" to cap1)))
                    )
                ),
                "v2" to VideoInfoFetchResult.Success(
                    FetchedVideoInfo("v2", "No Captions Video", "https://www.youtube.com/watch?v=v2", captionTracks = emptyList())
                ),
                "v3" to VideoInfoFetchResult.Success(
                    FetchedVideoInfo(
                        videoId = "v3",
                        title = "Video Three",
                        url = "https://www.youtube.com/watch?v=v3",
                        captionTracks = listOf(CaptionTrackCandidate("en", "English", true, mapOf("json3" to cap3)))
                    )
                )
            ),
            payloads = mapOf(
                cap1 to { Result.success("WEBVTT\n\n00:00:00.000 --> 00:00:02.000\nFirst transcript.") },
                cap3 to { Result.success("""{"events":[{"tStartMs":1000,"dDurationMs":2000,"segs":[{"utf8":"Third transcript."}]}]}""") }
            )
        )

        val progressEvents = mutableListOf<TranscriptExtractionProgress>()
        val extractor = YouTubeTranscriptExtractor(ds, clock = { 1700000000000L })
        val outcome = extractor.extract(
            rawUrl = "https://www.youtube.com/playlist?list=PLmixed",
            preference = TranscriptTargetPreference.PLAYLIST,
            onProgress = { progressEvents.add(it) }
        ) as TranscriptExtractionOutcome.Completed

        val doc = outcome.document
        assertTrue(doc.isPlaylist)
        assertEquals(4, doc.videosFound)
        assertEquals(2, doc.successfulCount)
        assertEquals(1, doc.noCaptionsCount)
        assertEquals(1, doc.inaccessibleCount)
        assertEquals(listOf("v1", "v2", "v3", "v4"), doc.entries.map { it.videoId })
        assertEquals(VideoTranscriptStatus.SUCCESS, doc.entries[0].status)
        assertEquals(VideoTranscriptStatus.NO_CAPTIONS, doc.entries[1].status)
        assertEquals(VideoTranscriptStatus.SUCCESS, doc.entries[2].status)
        assertEquals(VideoTranscriptStatus.ACCESS_ERROR, doc.entries[3].status)
        assertTrue(progressEvents.any { it.message == "Extracting video 1 of 4" })
        assertTrue(progressEvents.any { it.message == "Extracting video 4 of 4" })
        assertEquals(TranscriptExtractionStage.COMPLETED, progressEvents.last().stage)
    }

    @Test
    fun extract_cancelledMidPlaylist_returnsPartialDocumentWithoutDiscardingCompletedEntries() = runTest {
        val cap1 = "https://captions.test/p1.vtt"
        val entries = (1..4).map { idx ->
            PlaylistEntrySummary(idx, "v$idx", "Video $idx", "https://www.youtube.com/watch?v=v$idx")
        }
        val ds = FakeTranscriptDataSource(
            playlists = mapOf(
                "PLcancel" to PlaylistFetchResult.Success(
                    PlaylistResolution("PLcancel", "Long Playlist", "https://www.youtube.com/playlist?list=PLcancel", 4, entries)
                )
            ),
            videos = entries.associate { e ->
                e.videoId to VideoInfoFetchResult.Success(
                    FetchedVideoInfo(
                        e.videoId,
                        e.title,
                        e.url,
                        captionTracks = listOf(CaptionTrackCandidate("en", "English", false, mapOf("vtt" to cap1)))
                    )
                )
            },
            payloads = mapOf(cap1 to { Result.success("WEBVTT\n\n00:00:00.000 --> 00:00:02.000\nLine one.") }),
            perVideoDelayMs = 80L
        )

        val extractor = YouTubeTranscriptExtractor(ds, clock = { 1700000000000L })
        val job = async {
            extractor.extract(
                rawUrl = "https://www.youtube.com/playlist?list=PLcancel",
                preference = TranscriptTargetPreference.PLAYLIST
            )
        }
        delay(190L)
        job.cancel(CancellationException("User cancelled"))

        // Verify cancellation was propagated cleanly without hanging; run again verifying cooperative progress cancel
        val dsFast = FakeTranscriptDataSource(
            playlists = mapOf(
                "PLcancel2" to PlaylistFetchResult.Success(
                    PlaylistResolution("PLcancel2", "Partial Playlist", "https://www.youtube.com/playlist?list=PLcancel2", 3, entries.take(3))
                )
            ),
            videos = entries.take(3).associate { e ->
                e.videoId to VideoInfoFetchResult.Success(
                    FetchedVideoInfo(e.videoId, e.title, e.url, captionTracks = listOf(CaptionTrackCandidate("en", "English", false, mapOf("vtt" to cap1))))
                )
            },
            payloads = mapOf(cap1 to { Result.success("WEBVTT\n\n00:00:00.000 --> 00:00:02.000\nLine one.") })
        )
        val job2 = async {
            YouTubeTranscriptExtractor(dsFast).extract(
                rawUrl = "https://www.youtube.com/playlist?list=PLcancel2",
                onProgress = { prog ->
                    if (prog.stage == TranscriptExtractionStage.EXTRACTING_VIDEO && prog.currentVideoIndex == 2) {
                        throw CancellationException("Cancel on video 2")
                    }
                }
            )
        }
        val res2 = job2.await()
        assertTrue(res2 is TranscriptExtractionOutcome.Cancelled)
        val partial = (res2 as TranscriptExtractionOutcome.Cancelled).partialDocument
        assertNotNull(partial)
        assertEquals(1, partial!!.entries.size)
        assertEquals("v1", partial.entries.single().videoId)
        assertTrue(partial.hasAnySuccessfulTranscript)
    }

    @Test
    fun dataSource_parsesYtDlpJsonAndWatchHtmlFallbackAndPaginatedPlaylistJson() = runTest {
        val context = RuntimeEnvironment.getApplication()
        val server = MockWebServer()
        server.start()
        try {
            val playlistPage1 = """
                {
                  "id": "PL123",
                  "title": "Architecture Talks",
                  "playlist_count": 52,
                  "entries": [
                    ${(1..50).joinToString(",") { """{"id":"vid_$it","title":"Talk $it","duration":600}""" }}
                  ]
                }
            """.trimIndent()
            val playlistPage2 = """
                {
                  "id": "PL123",
                  "title": "Architecture Talks",
                  "playlist_count": 52,
                  "entries": [
                    {"id":"vid_51","title":"Talk 51","duration":420},
                    {"id":"vid_52","title":"[Private video]","availability":"private"}
                  ]
                }
            """.trimIndent()

            var callNum = 0
            val dataSource = LaterboxYouTubeTranscriptDataSource(
                appContext = context,
                runtimeManager = YtDlpRuntimeManager(context),
                customExecutor = { req ->
                    callNum++
                    val out = if (callNum == 1) playlistPage1 else playlistPage2
                    com.yausername.youtubedl_android.YoutubeDLResponse(listOf<String?>(), 0, 10L, out, "")
                }
            )

            val plResult = dataSource.fetchPlaylistEntries(
                playlistId = "PL123",
                playlistUrl = "https://www.youtube.com/playlist?list=PL123",
                processId = "test_pl",
                onPageLoaded = { _, _ -> }
            ) as PlaylistFetchResult.Success

            assertEquals("Architecture Talks", plResult.playlist.title)
            assertEquals(52, plResult.playlist.entries.size)
            assertEquals("vid_1", plResult.playlist.entries.first().videoId)
            assertEquals(1, plResult.playlist.entries.first().position)
            assertEquals(52, plResult.playlist.entries.last().position)
            assertEquals(VideoTranscriptStatus.ACCESS_ERROR, plResult.playlist.entries.last().unavailabilityStatus)

            // Verify watch HTML playerResponse parser fallback
            val html = """
                <html><head><script>
                var ytInitialPlayerResponse = {"playabilityStatus":{"status":"OK"},"videoDetails":{"videoId":"xyz","title":"HTML Parsed Video","author":"Tech Channel","lengthSeconds":"125"},"captions":{"playerCaptionsTracklistRenderer":{"captionTracks":[{"baseUrl":"${server.url("/timedtext?v=xyz")}","languageCode":"en","name":{"simpleText":"English"}}]}}};
                </script></head></html>
            """.trimIndent()
            val htmlInfo = dataSource.parseWatchHtmlPlayerResponse("xyz", "https://www.youtube.com/watch?v=xyz", html)
            assertTrue(htmlInfo is VideoInfoFetchResult.Success)
            val parsed = (htmlInfo as VideoInfoFetchResult.Success).info
            assertEquals("HTML Parsed Video", parsed.title)
            assertEquals("Tech Channel", parsed.channel)
            assertEquals(125L, parsed.durationSeconds)
            assertEquals(1, parsed.captionTracks.size)

            server.enqueue(MockResponse().setResponseCode(200).setBody("WEBVTT\n\n00:00:00.000 --> 00:00:02.000\nCaption OK"))
            val captionFetch = dataSource.fetchCaptionPayload(server.url("/timedtext?v=xyz").toString())
            assertTrue(captionFetch.isSuccess)
            assertTrue(captionFetch.getOrThrow().contains("Caption OK"))
        } finally {
            server.shutdown()
        }
    }
