package com.laterbox.app.transcript.data

import com.laterbox.app.transcript.domain.CaptionTrackCandidate
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class CaptionTrackParserAndSelectorTest {

    @Test
    fun selectBest_prefersEnglishAndManualOverAutoGeneratedAndJson3Format() {
        val tracks = listOf(
            CaptionTrackCandidate(
                languageCode = "es",
                languageName = "Spanish",
                isAutoGenerated = false,
                formatUrls = mapOf("json3" to "https://example.com/es.json3")
            ),
            CaptionTrackCandidate(
                languageCode = "en-US",
                languageName = "English (auto-generated)",
                isAutoGenerated = true,
                formatUrls = mapOf("json3" to "https://example.com/en-auto.json3")
            ),
            CaptionTrackCandidate(
                languageCode = "en-GB",
                languageName = "English (UK)",
                isAutoGenerated = false,
                formatUrls = mapOf(
                    "vtt" to "https://example.com/en-gb.vtt",
                    "json3" to "https://example.com/en-gb.json3"
                )
            )
        )

        val selected = CaptionLanguageSelector.selectBest(tracks)
        assertNotNull(selected)
        assertEquals("en-GB", selected!!.track.languageCode)
        assertFalse(selected.track.isAutoGenerated)
        assertEquals("json3", selected.format)
        assertEquals("https://example.com/en-gb.json3", selected.url)
        assertEquals("English (UK)", CaptionLanguageSelector.formatDisplayLanguage(selected.track))
    }

    @Test
    fun selectBest_fallsBackToAutoEnglishThenOtherLanguageWhenManualEnglishUnavailable() {
        val onlyAutoEnglish = listOf(
            CaptionTrackCandidate("fr", "French", false, mapOf("vtt" to "https://example.com/fr.vtt")),
            CaptionTrackCandidate("en", "English (auto-generated)", true, mapOf("srv3" to "https://example.com/en.srv3"))
        )
        val pick1 = CaptionLanguageSelector.selectBest(onlyAutoEnglish)
        assertNotNull(pick1)
        assertEquals("en", pick1!!.track.languageCode)
        assertTrue(pick1.track.isAutoGenerated)
        assertEquals("srv3", pick1.format)
        assertEquals("English", CaptionLanguageSelector.formatDisplayLanguage(pick1.track))

        val noEnglish = listOf(
            CaptionTrackCandidate("de", "German", true, mapOf("vtt" to "https://example.com/de-auto.vtt")),
            CaptionTrackCandidate("de", "German", false, mapOf("vtt" to "https://example.com/de.vtt"))
        )
        val pick2 = CaptionLanguageSelector.selectBest(noEnglish)
        assertNotNull(pick2)
        assertFalse(pick2!!.track.isAutoGenerated)

        assertNull(CaptionLanguageSelector.selectBest(emptyList()))
    }

    @Test
    fun parseJson3_preservesExactWordingAndParagraphBreaksAndTimestamps() {
        val json3 = """
            {
              "events": [
                {
                  "tStartMs": 0,
                  "dDurationMs": 3200,
                  "segs": [
                    { "utf8": "Welcome back to the " },
                    { "utf8": "systems design walkthrough." }
                  ]
                },
                {
                  "tStartMs": 3200,
                  "dDurationMs": 100,
                  "segs": [ { "utf8": "\n\n" } ]
                },
                {
                  "tStartMs": 35000,
                  "dDurationMs": 4500,
                  "segs": [
                    { "utf8": "The second section focuses on caching." }
                  ]
                }
              ]
            }
        """.trimIndent()

        val parsed = CaptionTrackParser.parse(json3, formatHint = "json3")
        assertEquals(2, parsed.segments.size)
        assertEquals(2, parsed.paragraphs.size)
        assertEquals(0L, parsed.paragraphs[0].startMs)
        assertEquals("Welcome back to the systems design walkthrough.", parsed.paragraphs[0].text)
        assertEquals(35000L, parsed.paragraphs[1].startMs)
        assertEquals("The second section focuses on caching.", parsed.paragraphs[1].text)
    }

    @Test
    fun parseVtt_deduplicatesRollingCaptionOverlapAndStripsInlineTags() {
        val vtt = """
            WEBVTT
            Kind: captions
            Language: en

            00:00:01.000 --> 00:00:03.000
            First line spoken here
            <c>second line begins</c>

            00:00:03.000 --> 00:00:06.000
            <c>second line begins</c>
            and third line follows.

            00:00:10.500 --> 00:00:13.000
            Completely new sentence after gap.
        """.trimIndent()

        val parsed = CaptionTrackParser.parse(vtt, formatHint = "vtt")
        assertEquals(3, parsed.segments.size)
        assertEquals("First line spoken here second line begins", parsed.segments[0].text)
        assertEquals("and third line follows.", parsed.segments[1].text)
        assertEquals("Completely new sentence after gap.", parsed.segments[2].text)
        assertEquals(10_500L, parsed.paragraphs[1].startMs)
    }

    @Test
    fun parseXmlSrv1AndSrv3_unescapesEntitiesVerbatim() {
        val srv1 = """
            <?xml version="1.0" encoding="utf-8" ?>
            <transcript>
              <text start="0.5" dur="2.5">Tom &amp; Jerry say &quot;Hello&quot;</text>
              <text start="6.5" dur="2.0">Next topic starts after a 3.5s pause.</text>
            </transcript>
        """.trimIndent()

        val parsedSrv1 = CaptionTrackParser.parse(srv1, formatHint = "srv1")
        assertEquals(2, parsedSrv1.segments.size)
        assertEquals(500L, parsedSrv1.segments[0].startMs)
        assertEquals("Tom & Jerry say \"Hello\"", parsedSrv1.segments[0].text)
        assertEquals(2, parsedSrv1.paragraphs.size)

        val srv3 = """
            <timedtext format="3">
              <body>
                <p t="12000" d="3000">Measured in 50ms &lt; latency budget.</p>
              </body>
            </timedtext>
        """.trimIndent()
        val parsedSrv3 = CaptionTrackParser.parse(srv3, formatHint = "srv3")
        assertEquals(1, parsedSrv3.segments.size)
        assertEquals(12000L, parsedSrv3.segments[0].startMs)
        assertEquals("Measured in 50ms < latency budget.", parsedSrv3.segments[0].text)
    }
}
